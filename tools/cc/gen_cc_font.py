rom = [0] * (256 * 16)
for code in range(256):
    rows = None
    if code in acc:
        rows = list(acc[code]) + ['.....'] * 3
    elif 0x20 <= code < 0x80 and chr(code) in G:
        rows = G[chr(code)]
    if rows:
        for r, bits in enumerate(rows):
            v = 0
            for i, b in enumerate(bits):
                if b == '#':
                    v |= 1 << (4 - i)
            rom[code * 16 + r] = v
missing = [hex(c) for c in range(0x20, 0x80) if c not in acc and chr(c) not in G]
